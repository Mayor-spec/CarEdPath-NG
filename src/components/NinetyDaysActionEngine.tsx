import React, { useState } from 'react';
import { motion, AnimatePresence } from 'motion/react';
import { get90DayPlanForCareer, Career90DayPlan, ActionMission } from '../data/ninetyDaysData';

interface NinetyDaysActionEngineProps {
  careerAmbition: string;
  activeAlternateScenarioTitle?: string | null;
}

export const NinetyDaysActionEngine: React.FC<NinetyDaysActionEngineProps> = ({
  careerAmbition,
  activeAlternateScenarioTitle
}) => {
  const plan: Career90DayPlan = get90DayPlanForCareer(careerAmbition);
  const [completedMissionIds, setCompletedMissionIds] = useState<Record<string, boolean>>({});
  const [copiedStatus, setCopiedStatus] = useState<string | null>(null);
  const [showScriptModal, setShowScriptModal] = useState<boolean>(false);

  const completedCount = plan.missions.filter((m) => !!completedMissionIds[m.id]).length;
  const totalMissions = plan.missions.length;
  const readinessScore = Math.round((completedCount / totalMissions) * 100);

  const toggleMission = (id: string) => {
    setCompletedMissionIds((prev) => ({
      ...prev,
      [id]: !prev[id]
    }));
  };

  // Copy checklist to clipboard
  const handleCopyChecklist = () => {
    const lines = [
      `CarEdPath NG — MY NEXT 90 DAYS: 3 CONCRETE MISSIONS`,
      `Target Career: ${plan.careerTitle}`,
      `Readiness Score: ${readinessScore}% (${completedCount} of ${totalMissions} Completed)`,
      '',
      ...plan.missions.map((m) => {
        const isDone = !!completedMissionIds[m.id];
        const box = isDone ? '[X]' : '[ ]';
        return `${box} Mission ${m.categoryNumber} (${m.categoryLabel}):\n   ${m.concreteAction}\n   Recommended: ${m.recommendedResource.name} | ${m.recommendedResource.platform}\n   Deliverable: ${m.deliverable}\n`;
      }),
      `Generated by CarEdPath NG (Empowering Nigerian Secondary Students in Higher Education)`
    ];

    navigator.clipboard.writeText(lines.join('\n')).then(() => {
      setCopiedStatus('Checklist Copied!');
      setTimeout(() => setCopiedStatus(null), 3000);
    }).catch(() => {
      setCopiedStatus('Failed to copy');
      setTimeout(() => setCopiedStatus(null), 3000);
    });
  };

  // Motivational caption based on score
  const getScoreBadge = () => {
    if (readinessScore === 100) {
      return {
        text: 'Fully Mission Ready! 🚀',
        color: 'bg-emerald-600 text-white',
        desc: 'You have completed all 3 core missions. You are ahead of 90% of applicants in Nigeria!'
      };
    }
    if (readinessScore >= 66) {
      return {
        text: '2/3 Complete • Fast Track 🔥',
        color: 'bg-orange-600 text-white',
        desc: 'Exceptional momentum! Finish the last mission to lock in your 90-day baseline.'
      };
    }
    if (readinessScore >= 33) {
      return {
        text: '1/3 Complete • Strong Start 🌱',
        color: 'bg-blue-600 text-white',
        desc: 'First concrete milestone achieved. Keep going with Mission 2 practical discovery!'
      };
    }
    return {
      text: '0% • Ready to Launch 🎯',
      color: 'bg-slate-700 text-white',
      desc: 'Tap the checkboxes as you finish each task over the next 3 months.'
    };
  };

  const scoreBadge = getScoreBadge();

  return (
    <div
      id="ninety-days-engine-root"
      className="mt-8 pt-8 border-t-2 border-slate-200/90 flex flex-col gap-6"
    >
      {/* High-Priority Section Header with Touch of Terracotta & Emerald */}
      <div className="flex flex-col md:flex-row md:items-center md:justify-between gap-4 bg-gradient-to-r from-slate-50 via-orange-50/40 to-slate-50 p-5 sm:p-6 rounded-2xl border border-slate-200 shadow-xs">
        <div className="flex flex-col gap-1.5">
          <div className="flex items-center gap-2 flex-wrap">
            <span className="px-3 py-1 rounded-full text-[11px] font-bold uppercase tracking-wider bg-[#c85a32] text-white shadow-xs">
              Concrete Action Plan
            </span>
            <span className="px-2.5 py-0.5 rounded-full text-[11px] font-semibold bg-white border border-slate-200 text-slate-700">
              No Overwhelm • 3 High-Impact Steps
            </span>
          </div>

          <h3 className="font-serif-headline text-[20px] sm:text-[24px] font-bold text-[#0a192f] leading-tight mt-1">
            Your Next 90 Days: 3 Concrete Missions
          </h3>
          <p className="text-[13px] text-slate-600 max-w-2xl leading-relaxed">
            Don’t wait until JAMB registration day or university resumption. These three high-yield missions build your academic mastery, hands-on portfolio, and senior network immediately.
          </p>
        </div>

        {/* 90-Day Readiness Score Meter Box */}
        <div className="flex flex-col p-4 rounded-xl bg-white border border-slate-200/90 shadow-2xs min-w-[240px]">
          <div className="flex items-center justify-between gap-2 mb-1.5">
            <span className="text-[11px] font-bold uppercase tracking-wider text-slate-500">
              90-Day Readiness Score
            </span>
            <span className="font-mono text-[16px] font-extrabold text-[#0a192f]">
              {readinessScore}%
            </span>
          </div>

          {/* Animated Progress Track */}
          <div className="w-full h-3 bg-slate-100 rounded-full overflow-hidden p-0.5 border border-slate-200">
            <motion.div
              initial={{ width: 0 }}
              animate={{ width: `${readinessScore}%` }}
              transition={{ duration: 0.5, ease: 'easeOut' }}
              className={`h-full rounded-full transition-colors ${
                readinessScore === 100
                  ? 'bg-emerald-500'
                  : readinessScore >= 66
                  ? 'bg-[#c85a32]'
                  : readinessScore >= 33
                  ? 'bg-blue-600'
                  : 'bg-slate-300'
              }`}
            />
          </div>

          <div className="flex items-center justify-between mt-2">
            <span className={`text-[10px] font-bold px-2 py-0.5 rounded-md ${scoreBadge.color}`}>
              {scoreBadge.text}
            </span>
            <span className="text-[11px] text-slate-500 font-semibold">
              {completedCount} of {totalMissions} Missions Done
            </span>
          </div>
        </div>
      </div>

      {/* 3 Distinct Mission Cards Grid */}
      <div className="grid grid-cols-1 lg:grid-cols-3 gap-4 sm:gap-5">
        {plan.missions.map((mission) => {
          const isChecked = !!completedMissionIds[mission.id];

          // Distinct visual styles by category
          const categoryStyle = {
            1: {
              badge: 'bg-blue-100 text-blue-900 border-blue-200',
              accent: 'border-l-4 border-l-blue-600',
              icon: 'school',
              numBg: 'bg-blue-700'
            },
            2: {
              badge: 'bg-emerald-100 text-emerald-900 border-emerald-200',
              accent: 'border-l-4 border-l-emerald-600',
              icon: 'handyman',
              numBg: 'bg-emerald-700'
            },
            3: {
              badge: 'bg-orange-100 text-[#9c3e1e] border-orange-200',
              accent: 'border-l-4 border-l-[#c85a32]',
              icon: 'diversity_3',
              numBg: 'bg-[#c85a32]'
            }
          }[mission.categoryNumber];

          return (
            <motion.div
              key={mission.id}
              id={`mission-card-${mission.id}`}
              whileHover={{ y: -3 }}
              transition={{ duration: 0.2 }}
              className={`relative rounded-2xl p-5 bg-white border transition-all flex flex-col justify-between shadow-2xs ${
                isChecked
                  ? 'border-emerald-400 ring-2 ring-emerald-100 bg-emerald-50/20'
                  : 'border-slate-200 hover:border-slate-300 hover:shadow-sm'
              } ${categoryStyle.accent}`}
            >
              {/* Card Header with Custom Checkbox */}
              <div>
                <div className="flex items-start justify-between gap-3 pb-3 border-b border-slate-100">
                  <div className="flex items-center gap-2">
                    <span className={`w-6 h-6 rounded-full text-white text-[11px] font-bold flex items-center justify-center ${categoryStyle.numBg}`}>
                      {mission.categoryNumber}
                    </span>
                    <span className={`px-2 py-0.5 rounded-md text-[10.5px] font-bold uppercase tracking-wider border ${categoryStyle.badge}`}>
                      {mission.categoryLabel}
                    </span>
                  </div>

                  {/* Big Custom Interactive Checkbox */}
                  <label
                    htmlFor={`checkbox-${mission.id}`}
                    className="relative flex items-center gap-1.5 cursor-pointer select-none group"
                    onClick={(e) => e.stopPropagation()}
                  >
                    <input
                      id={`checkbox-${mission.id}`}
                      type="checkbox"
                      checked={isChecked}
                      onChange={() => toggleMission(mission.id)}
                      className="sr-only"
                    />
                    <div
                      className={`w-6 h-6 rounded-lg flex items-center justify-center border-2 transition-all ${
                        isChecked
                          ? 'bg-emerald-600 border-emerald-600 text-white shadow-xs'
                          : 'bg-white border-slate-300 group-hover:border-slate-400'
                      }`}
                    >
                      {isChecked && (
                        <span className="material-symbols-outlined text-[16px] font-bold">check</span>
                      )}
                    </div>
                    <span className="text-[11px] font-bold text-slate-600">
                      {isChecked ? 'Done' : 'Mark Done'}
                    </span>
                  </label>
                </div>

                {/* Mission Title & Concrete Action */}
                <div className="pt-3 flex flex-col gap-2">
                  <h4 className="font-serif-headline text-[16px] font-bold text-[#0a192f] leading-snug">
                    {mission.title}
                  </h4>

                  <p className="text-[13px] text-slate-700 leading-relaxed font-medium">
                    {mission.concreteAction}
                  </p>
                </div>

                {/* Recommended Platform & Time Commitment */}
                <div className="mt-3 pt-3 border-t border-slate-100 flex flex-col gap-2 text-[12px]">
                  <div className="p-2.5 rounded-xl bg-slate-50 border border-slate-200/70 flex flex-col gap-1">
                    <div className="flex items-center justify-between gap-1">
                      <span className="text-[10px] font-bold uppercase tracking-wider text-slate-500">
                        Zero-Cost Tool / Resource
                      </span>
                      <span className="text-[9.5px] font-bold px-1.5 py-0.5 rounded bg-emerald-100 text-emerald-800">
                        {mission.recommendedResource.badge}
                      </span>
                    </div>
                    <span className="font-semibold text-[#0a192f]">
                      {mission.recommendedResource.name}
                    </span>
                    <span className="text-[11px] text-slate-500">
                      Platform: {mission.recommendedResource.platform}
                    </span>
                  </div>

                  <div className="flex items-center gap-1.5 text-slate-600 text-[11.5px]">
                    <span className="material-symbols-outlined text-[15px] text-slate-400">timer</span>
                    <span>Pace: <strong>{mission.dailyTimeCommitment}</strong></span>
                  </div>

                  {/* Concrete Deliverable Box */}
                  <div className="p-2.5 rounded-xl bg-amber-50/60 border border-amber-200/70 text-amber-950 flex flex-col gap-0.5">
                    <span className="text-[10px] font-bold uppercase tracking-wider text-amber-800">
                      Tangible Deliverable:
                    </span>
                    <span className="text-[11.5px] leading-snug">
                      {mission.deliverable}
                    </span>
                  </div>
                </div>
              </div>

              {/* Mentor Tip Footer */}
              <div className="mt-4 pt-3 border-t border-slate-100 flex flex-col gap-2">
                <div className="text-[11.5px] text-slate-600 italic leading-snug">
                  💡 <strong>Mentor Pro-Tip:</strong> {mission.mentorTip}
                </div>

                {mission.categoryNumber === 3 && (
                  <button
                    type="button"
                    onClick={() => setShowScriptModal(true)}
                    className="mt-1 w-full py-1.5 px-2 rounded-lg bg-orange-50 hover:bg-orange-100 border border-orange-200 text-[#9c3e1e] font-bold text-[11px] flex items-center justify-center gap-1 cursor-pointer transition-colors"
                  >
                    <span className="material-symbols-outlined text-[14px]">chat</span>
                    <span>View Reach-Out Message Template</span>
                  </button>
                )}
              </div>
            </motion.div>
          );
        })}
      </div>

      {/* Action Toolbar: Clipboard Copy + Print / Save */}
      <div className="p-4 sm:p-5 rounded-2xl bg-white border border-slate-200 flex flex-col sm:flex-row items-center justify-between gap-3 shadow-xs">
        <div className="flex items-center gap-2.5 text-slate-600 text-[12.5px]">
          <span className="material-symbols-outlined text-[#0a192f] text-[22px]">
            checklist_rtl
          </span>
          <span>
            Keep yourself or your study partner accountable with your real-time mission progress.
          </span>
        </div>

        <div className="flex items-center gap-2 w-full sm:w-auto flex-wrap">
          <button
            id="copy-missions-btn"
            type="button"
            onClick={handleCopyChecklist}
            className="flex-1 sm:flex-initial px-4 py-2.5 rounded-xl text-[12.5px] font-semibold flex items-center justify-center gap-1.5 bg-[#0a192f] text-white hover:bg-slate-800 active:scale-95 transition-all shadow-sm cursor-pointer"
          >
            <span className="material-symbols-outlined text-[16px]">
              {copiedStatus ? 'check' : 'content_copy'}
            </span>
            <span>{copiedStatus || 'Copy 3 Missions'}</span>
          </button>

          <button
            id="print-missions-btn"
            type="button"
            onClick={() => window.print()}
            className="flex-1 sm:flex-initial px-3.5 py-2.5 rounded-xl text-[12.5px] font-semibold flex items-center justify-center gap-1.5 bg-slate-100 text-slate-700 hover:bg-slate-200 active:scale-95 transition-all cursor-pointer no-print"
          >
            <span className="material-symbols-outlined text-[16px]">print</span>
            <span>Print Checklist</span>
          </button>
        </div>
      </div>

      {/* Sisterhood Reach-Out Message Script Modal */}
      <AnimatePresence>
        {showScriptModal && (
          <div className="fixed inset-0 z-50 flex items-center justify-center p-4">
            <motion.div
              initial={{ opacity: 0 }}
              animate={{ opacity: 1 }}
              exit={{ opacity: 0 }}
              className="fixed inset-0 bg-[#0a192f]/70 backdrop-blur-xs"
              onClick={() => setShowScriptModal(false)}
            />

            <motion.div
              initial={{ scale: 0.94, opacity: 0, y: 15 }}
              animate={{ scale: 1, opacity: 1, y: 0 }}
              exit={{ scale: 0.94, opacity: 0, y: 15 }}
              className="relative w-full max-w-md bg-white rounded-2xl shadow-2xl border border-slate-200 z-10 p-5 flex flex-col gap-3 text-slate-900"
            >
              <div className="flex items-center justify-between border-b border-slate-100 pb-2.5">
                <div className="flex items-center gap-2">
                  <span className="material-symbols-outlined text-[#c85a32] text-[20px]">
                    outgoing_mail
                  </span>
                  <h4 className="font-serif-headline text-[16px] font-bold text-[#0a192f]">
                    Copy-Paste Outreach Message
                  </h4>
                </div>
                <button
                  type="button"
                  onClick={() => setShowScriptModal(false)}
                  className="text-slate-400 hover:text-slate-700 cursor-pointer"
                >
                  <span className="material-symbols-outlined text-[18px]">close</span>
                </button>
              </div>

              <p className="text-[12px] text-slate-600">
                Copy and personalize this polite message when reaching out to an admission mentor or university senior on LinkedIn, email, or a student STEM club:
              </p>

              <div className="p-3.5 rounded-xl bg-slate-50 border border-slate-200 text-[12.5px] text-slate-800 font-mono leading-relaxed whitespace-pre-wrap select-all">
{`Hello! Good day. My name is [Your Name], and I am a Nigerian secondary-school student currently preparing for admission into [Target University Name] to study [Course Name].

I saw your academic journey in university and was truly inspired! Whenever you have 5 spare minutes, I would be deeply grateful to ask 2 brief questions about how you prepared for UTME/JAMB and Post-UTME, and which textbooks were most helpful for secondary school transition.

Thank you so much for your time and encouragement!`}
              </div>

              <div className="flex gap-2 pt-1">
                <button
                  type="button"
                  onClick={() => {
                    const text = `Hello! Good day. My name is [Your Name], and I am a Nigerian secondary-school student currently preparing for admission into [Target University Name] to study [Course Name].\n\nI saw your academic journey in university and was truly inspired! Whenever you have 5 spare minutes, I would be deeply grateful to ask 2 brief questions about how you prepared for UTME/JAMB and Post-UTME, and which textbooks were most helpful for secondary school transition.\n\nThank you so much for your time and encouragement!`;
                    navigator.clipboard.writeText(text);
                    setCopiedStatus('Script Copied!');
                    setTimeout(() => setCopiedStatus(null), 2500);
                  }}
                  className="flex-1 py-2.5 rounded-xl bg-[#0a192f] text-white font-bold text-[12px] hover:bg-[#132644] cursor-pointer text-center"
                >
                  {copiedStatus === 'Script Copied!' ? 'Copied to Clipboard!' : 'Copy Template Message'}
                </button>
                <button
                  type="button"
                  onClick={() => setShowScriptModal(false)}
                  className="px-4 py-2.5 rounded-xl bg-slate-100 text-slate-700 font-bold text-[12px] hover:bg-slate-200 cursor-pointer"
                >
                  Close
                </button>
              </div>
            </motion.div>
          </div>
        )}
      </AnimatePresence>
    </div>
  );
};
